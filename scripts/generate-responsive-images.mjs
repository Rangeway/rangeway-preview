import { mkdir, readdir, stat, writeFile } from "node:fs/promises";
import path from "node:path";
import sharp from "sharp";

const imageDirectory = path.resolve("public/images");
const metadataPath = path.resolve("src/lib/image-metadata.mjs");

async function collectJpegs(directory) {
  const entries = await readdir(directory, { withFileTypes: true });
  const files = await Promise.all(entries.map(async (entry) => {
    const entryPath = path.join(directory, entry.name);
    if (entry.isDirectory()) return collectJpegs(entryPath);
    return /\.jpe?g$/i.test(entry.name) ? [entryPath] : [];
  }));
  return files.flat();
}

const metadata = {};
for (const sourcePath of await collectJpegs(imageDirectory)) {
  const image = sharp(sourcePath);
  const sourceMetadata = await image.metadata();
  const relativePath = `/${path.relative("public", sourcePath).split(path.sep).join("/")}`;

  metadata[relativePath] = {
    width: sourceMetadata.width,
    height: sourceMetadata.height
  };

  if ((sourceMetadata.width ?? 0) > 640) {
    const variantPath = sourcePath.replace(/\.jpe?g$/i, "-640.webp");
    const [sourceStats, variantStats] = await Promise.all([
      stat(sourcePath),
      stat(variantPath).catch(() => undefined)
    ]);

    if (!variantStats || variantStats.mtimeMs < sourceStats.mtimeMs) {
      await image.rotate().resize({ width: 640, withoutEnlargement: true }).webp({ quality: 80 }).toFile(variantPath);
    }
  }
}

await mkdir(path.dirname(metadataPath), { recursive: true });
await writeFile(
  metadataPath,
  `// Generated by scripts/generate-responsive-images.mjs.\nexport const imageMetadata = ${JSON.stringify(metadata, null, 2)};\n`
);
